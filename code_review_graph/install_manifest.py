"""The record of the files ``install`` wrote inside the repository.

``install`` writes ``.code-review-graph/install-manifest.json``::

    {"version": 1, "files": ["<repo-relative POSIX path>", ...]}

Each install merges the files it writes into the record and never drops one,
so a reinstall that finds a file already up to date keeps it listed.
``uninstall`` drops each path it removes or cleans, and deletes the record
when it is empty. Build and change discovery leave out a listed path that git
does not track, so ``.mcp.json``, ``.claude/settings.json`` and the other
files ``install`` just wrote are not reviewed as the user's own changes.

Paths outside the repository, inside ``.git`` or inside ``.code-review-graph``
are never listed.
"""

from __future__ import annotations

import json
import logging
import os
import tempfile
from collections.abc import Iterable
from pathlib import Path, PurePath, PurePosixPath

from . import install_plan

logger = logging.getLogger(__name__)

DATA_DIR_NAME = ".code-review-graph"
MANIFEST_NAME = "install-manifest.json"
VERSION = 1

# What ``incremental._write_data_dir_gitignore`` writes, so a data folder this
# module creates keeps its files out of commits in the same way.
_DATA_DIR_GITIGNORE = (
    "# Auto-generated by code-review-graph — do not commit database files.\n"
    "# The graph.db contains absolute paths and code structure metadata.\n"
    "*\n"
)


def manifest_path(repo_root: Path) -> Path:
    """Return where the record lives for ``repo_root``."""
    return repo_root / DATA_DIR_NAME / MANIFEST_NAME


def _relative(repo_root: Path, path: Path) -> str | None:
    """Return ``path`` relative to the repository as POSIX text, or None."""
    bases = {os.path.abspath(repo_root), os.path.realpath(repo_root)}
    for candidate in dict.fromkeys((os.path.abspath(path), os.path.realpath(path))):
        for base in bases:
            try:
                relative = os.path.relpath(candidate, base)
            except ValueError:  # another drive on Windows
                continue
            parts = PurePath(relative).parts
            if not parts or relative == "." or parts[0] == ".." or os.path.isabs(relative):
                continue
            if parts[0] in (".git", DATA_DIR_NAME):
                return None
            return PurePosixPath(*parts).as_posix()
    return None


def relative_paths(repo_root: Path, paths: Iterable[Path]) -> list[str]:
    """Return the paths inside the repository, relative to it, sorted and unique."""
    found = (_relative(repo_root, Path(path)) for path in paths)
    return sorted({path for path in found if path is not None})


def _parse(text: str) -> list[str] | None:
    """Return the listed files, or None when the text is not a record."""
    try:
        data = json.loads(text)
    except (json.JSONDecodeError, RecursionError):
        return None
    if not isinstance(data, dict) or data.get("version") != VERSION:
        return None
    files = data.get("files")
    if not isinstance(files, list) or not all(isinstance(item, str) for item in files):
        return None
    return list(files)


def read(repo_root: Path) -> list[str]:
    """Return the repo-relative paths ``install`` recorded, or ``[]``.

    A missing, unreadable or malformed record counts as empty: it only ever
    narrows what is reviewed, so guessing at a damaged one would be worse.
    """
    path = manifest_path(repo_root)
    try:
        text = install_plan.read_text(path, encoding="utf-8")
    except (OSError, UnicodeError):
        return []
    files = _parse(text)
    if files is None:
        logger.warning("Ignoring %s: it is not an install record this version reads.", path)
        return []
    return files


def _render(files: Iterable[str]) -> str:
    return json.dumps({"version": VERSION, "files": sorted(set(files))}, indent=2) + "\n"


def plan_record(repo_root: Path, plan: install_plan.Plan) -> None:
    """Add the updated record to ``plan``, listing every file the plan writes.

    The files already listed stay listed. Nothing is planned when the record
    would not change, so a reinstall that writes nothing writes no record.
    """
    written = relative_paths(repo_root, plan.written())
    existing = read(repo_root)
    merged = sorted(set(existing) | set(written))
    path = manifest_path(repo_root)
    if not merged or (merged == sorted(set(existing)) and install_plan.exists(path)):
        return
    data_dir = path.parent
    if not install_plan.lexists(data_dir):
        # A new data folder gets the same inner .gitignore a build would give it.
        install_plan.write_text(data_dir / ".gitignore", _DATA_DIR_GITIGNORE)
    install_plan.write_text(path, _render(merged))


def forget(repo_root: Path, paths: Iterable[Path]) -> None:
    """Drop ``paths`` from the record; delete the record when nothing is left.

    Called by ``uninstall`` for each file it removed or cleaned, so a file
    that is the user's alone again is reviewed like any other.
    """
    path = manifest_path(repo_root)
    if not path.is_file() or path.is_symlink():
        return
    existing = read(repo_root)
    gone = set(relative_paths(repo_root, paths))
    kept = [item for item in existing if item not in gone]
    if kept == existing:
        return
    try:
        if not kept:
            path.unlink()
            return
        _replace(path, _render(kept))
    except OSError as exc:
        logger.warning("Could not update %s: %s", path, exc)


def _replace(path: Path, text: str) -> None:
    """Write ``text`` to ``path`` in one step, so a reader never sees half a file."""
    with tempfile.NamedTemporaryFile(
        "w", encoding="utf-8", dir=path.parent, prefix=f".{path.name}.", suffix=".tmp",
        delete=False,
    ) as handle:
        temporary = Path(handle.name)
        handle.write(text)
    try:
        os.replace(temporary, path)
    except OSError:
        temporary.unlink(missing_ok=True)
        raise
